'use client';

import { useEffect, useRef } from 'react';
import { ExternalLink, X } from 'lucide-react';
import { getDialogTitle } from '@/components/airindx/format';
import { AirIndxTimestamp, AirIndxWeatherDetails } from '@/components/airindx/AirIndxLocationPopup';
import { aqiTextColor } from '@/components/airindx/format';
import type { AirIndxDialogKind, AirIndxMarker } from '@/types/airindx';

interface AirIndxDialogProps {
  kind: Exclude<AirIndxDialogKind, null>;
  markers: AirIndxMarker[];
  selectedMarker: AirIndxMarker | null;
  riskPercent: number;
  onSelectMarker: (id: string) => void;
  onClose: () => void;
}

const FOCUSABLE_SELECTOR =
  'a[href], button:not([disabled]), input:not([disabled]), select:not([disabled]), textarea:not([disabled]), [tabindex]:not([tabindex="-1"])';

export function AirIndxDialog({
  kind,
  markers,
  selectedMarker,
  riskPercent,
  onSelectMarker,
  onClose,
}: AirIndxDialogProps) {
  const dialogRef = useRef<HTMLDivElement>(null);
  const closeRef = useRef<HTMLButtonElement>(null);

  useEffect(() => {
    const previouslyFocused = document.activeElement instanceof HTMLElement ? document.activeElement : null;
    closeRef.current?.focus();

    const handleKeyDown = (event: KeyboardEvent) => {
      if (event.key === 'Escape') {
        event.stopPropagation();
        onClose();
        return;
      }
      if (event.key !== 'Tab') return;
      const focusable = dialogRef.current?.querySelectorAll<HTMLElement>(FOCUSABLE_SELECTOR);
      if (!focusable || focusable.length === 0) return;
      const first = focusable[0];
      const last = focusable[focusable.length - 1];
      if (event.shiftKey && document.activeElement === first) {
        event.preventDefault();
        last.focus();
      } else if (!event.shiftKey && document.activeElement === last) {
        event.preventDefault();
        first.focus();
      }
    };

    document.addEventListener('keydown', handleKeyDown);
    return () => {
      document.removeEventListener('keydown', handleKeyDown);
      previouslyFocused?.focus();
    };
  }, [onClose]);

  return (
    <div
      className="fixed inset-0 z-50 flex items-center justify-center bg-[#030617]/75 p-4 backdrop-blur-md"
      role="presentation"
      onClick={onClose}
    >
      <div
        ref={dialogRef}
        role="dialog"
        aria-modal="true"
        aria-labelledby="airindx-dialog-title"
        tabIndex={-1}
        onClick={(event) => event.stopPropagation()}
        className="airindx-popup max-h-[90vh] w-full max-w-lg overflow-y-auto rounded-3xl border border-white/10 bg-[#0b1233]/95 p-6 text-slate-200 shadow-2xl"
      >
        <div className="flex items-start justify-between gap-4">
          <h2 id="airindx-dialog-title" className="text-xl font-bold text-white">
            {getDialogTitle(kind, selectedMarker)}
          </h2>
          <button
            ref={closeRef}
            type="button"
            onClick={onClose}
            aria-label="Close dialog"
            className="min-h-11 min-w-11 rounded-xl border border-white/10 bg-white/5 p-2 text-slate-300 hover:bg-white/10"
          >
            <X className="h-4 w-4" aria-hidden="true" />
          </button>
        </div>
        <div className="mt-4 space-y-3 text-sm leading-relaxed text-slate-300">
          <DialogContent
            kind={kind}
            markers={markers}
            selectedMarker={selectedMarker}
            riskPercent={riskPercent}
            onSelectMarker={onSelectMarker}
            onClose={onClose}
          />
        </div>
      </div>
    </div>
  );
}

function DialogContent({
  kind,
  markers,
  selectedMarker,
  riskPercent,
  onSelectMarker,
  onClose,
}: Omit<AirIndxDialogProps, 'onClose'> & { onClose: () => void }) {
  switch (kind) {
    case 'about':
      return (
        <p>
          AirIndx is an environmental intelligence interface for exploring current air quality across cities. It combines
          live atmospheric model data with an interactive globe so patterns are easier to understand at a glance.
        </p>
      );
    case 'technology':
      return (
        <>
          <p>
            Readings come from the Open-Meteo CAMS global air-quality and weather feeds through the BreatheWise API.
            US EPA AQI categories are computed server-side; no value shown here is generated by a language model.
          </p>
          <p>
            The globe uses React Three Fiber, Drei, and Three.js with local satellite, night-light, specular, and normal
            textures. The map view uses OpenStreetMap tiles.
          </p>
        </>
      );
    case 'monitors':
      return (
        <>
          <p>Each glowing marker represents one city grid reading. Select a marker to inspect its current AQI and weather.</p>
          <div className="mt-4 grid grid-cols-2 gap-2 sm:grid-cols-4">
            {markers.map((marker) => (
              <button
                key={marker.id}
                type="button"
                onClick={() => {
                  onSelectMarker(marker.id);
                  onClose();
                }}
                className="min-h-11 rounded-xl border border-white/10 bg-white/5 px-3 py-2 text-left text-xs text-slate-300 transition hover:border-cyan-300/40 hover:bg-cyan-400/10"
              >
                <span className="block font-semibold text-white">{marker.name}</span>
                <span style={{ color: marker.colorHex }}>{marker.aqi} AQI</span>
              </button>
            ))}
          </div>
        </>
      );
    case 'discover':
      return (
        <>
          <p>Compare marker colors to see where cleaner air and elevated pollution overlap across regions.</p>
          <ul className="mt-4 space-y-2 text-sm text-slate-300">
            <li>Green: Good, up to 50 AQI.</li>
            <li>Yellow: Moderate, up to 100 AQI.</li>
            <li>Orange: Unhealthy for sensitive groups, up to 150 AQI.</li>
            <li>Red: Unhealthy, up to 200 AQI.</li>
            <li>Purple: Very unhealthy, up to 300 AQI.</li>
            <li>Maroon: Hazardous, above 300 AQI.</li>
          </ul>
        </>
      );
    case 'risk':
      return (
        <>
          <p>
            The percentage is a simple presentation indicator derived from the selected city’s US AQI
            (AQI ÷ 300, capped at 100). It is not a medical probability or an official risk forecast.
          </p>
          {selectedMarker && (
            <p className="text-cyan-200">
              {selectedMarker.name}: {selectedMarker.aqi} AQI → {riskPercent}% indicator.
            </p>
          )}
        </>
      );
    case 'location':
      if (!selectedMarker) return <p>Location details are unavailable.</p>;
      return (
        <>
          <p>
            {selectedMarker.name}, {selectedMarker.country} is currently at {selectedMarker.aqi} US AQI —{' '}
            {selectedMarker.category}. Dominant pollutant: {selectedMarker.dominantPollutant}.
          </p>
          <AirIndxWeatherDetails marker={selectedMarker} />
          <AirIndxTimestamp marker={selectedMarker} />
          <a
            href={selectedMarker.sourceUrl}
            target="_blank"
            rel="noopener noreferrer"
            className="mt-3 inline-flex min-h-11 items-center gap-1 text-sm font-semibold text-cyan-300 hover:underline"
          >
            View source documentation <ExternalLink className="h-3.5 w-3.5" aria-hidden="true" />
          </a>
          <p className="text-xs text-slate-400">
            AQI badge color:{' '}
            <span style={{ color: aqiTextColor(selectedMarker.colorHex), backgroundColor: selectedMarker.colorHex }} className="rounded px-1.5 py-0.5 font-bold">
              {selectedMarker.category}
            </span>
          </p>
        </>
      );
  }
}
